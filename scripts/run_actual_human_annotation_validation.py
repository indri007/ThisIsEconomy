#!/usr/bin/env python3
"""
Script: run_actual_human_annotation_validation.py
=================================================
1. Evaluasi IndoBERT pada set uji holdout group-aware (protokol v2, n = 1.058)
   terhadap label SILVER-STANDARD.
2. Evaluasi IndoBERT terhadap anotasi manusia, HANYA bila berkas anotasi nyata
   tersedia (data/annotation/annotator_1.csv; opsional adjudicated_gold.csv).

Versi sebelumnya mengisi "researcher_label" dengan menyalin silver_label untuk
79 dari 100 baris dan menuliskan 21 label sisanya langsung di dalam kode, lalu
menyebut hasilnya "anotasi pakar". Angka yang dihasilkan (akurasi 90%, kappa 0.8243)
tidak boleh dikutip sebagai validasi manusia. Versi ini tidak pernah menyalin
label silver atau model ke kolom label manusia.

Keluaran:
  results/INDOBERT_ACTUAL_HUMAN_VALIDATION_REPORT.json
  results/INDOBERT_ACTUAL_HUMAN_VALIDATION_REPORT.md
  reports/iaa_expert_model_agreement.json
"""

import json
from datetime import datetime, timezone
from pathlib import Path

import pandas as pd
from sklearn.metrics import (accuracy_score, classification_report, cohen_kappa_score,
                             confusion_matrix, f1_score, precision_score, recall_score)

BASE_DIR = Path(__file__).resolve().parent.parent
ANN_DIR = BASE_DIR / "data" / "annotation"
RESULTS_DIR = BASE_DIR / "results"
REPORTS_DIR = BASE_DIR / "reports"
for d in (RESULTS_DIR, REPORTS_DIR):
    d.mkdir(parents=True, exist_ok=True)

LABELS_6 = ["Jijik", "Percaya", "Netral", "Tertarik", "Marah", "Sedih"]


def metrics(y_true, y_pred):
    return {
        "n": int(len(y_true)),
        "accuracy": round(float(accuracy_score(y_true, y_pred)), 4),
        "macro_precision": round(float(precision_score(y_true, y_pred, average="macro", zero_division=0)), 4),
        "macro_recall": round(float(recall_score(y_true, y_pred, average="macro", zero_division=0)), 4),
        "macro_f1": round(float(f1_score(y_true, y_pred, average="macro", zero_division=0)), 4),
        "weighted_f1": round(float(f1_score(y_true, y_pred, average="weighted", zero_division=0)), 4),
    }


def main():
    # ── 1. Holdout vs silver labels ────────────────────────────────────
    test_path = RESULTS_DIR / "indobert_group_aware_v2" / "predictions_test.csv"
    df = pd.read_csv(test_path)
    y_true, y_pred = df["true_label"].astype(str), df["predicted_label"].astype(str)
    holdout = metrics(y_true, y_pred)
    holdout["reference_labels"] = "silver-standard (keyword/rule-assisted; not human-adjudicated)"
    rep = classification_report(y_true, y_pred, labels=LABELS_6, output_dict=True, zero_division=0)
    holdout["per_class"] = {
        lbl: {k: round(float(rep[lbl][k]), 4) for k in ("precision", "recall", "f1-score")} | {"support": int(rep[lbl]["support"])}
        for lbl in LABELS_6
    }
    holdout["confusion_matrix"] = {"labels": LABELS_6,
                                   "matrix": confusion_matrix(y_true, y_pred, labels=LABELS_6).tolist()}
    holdout["classes_absent_from_test_set"] = ["Bahagia", "Kaget", "Takut"]

    # ── 2. Human annotation (only if real files exist) ─────────────────
    human = {"status": "not_available",
             "note": ("No independent human annotation file found. Earlier values "
                      "(accuracy 0.90, kappa 0.8243, inter-human kappa 0.9135, Fleiss 0.8442, "
                      "Krippendorff 0.8447) were generated by scripted labels and are withdrawn.")}
    a1_path = ANN_DIR / "annotator_1.csv"
    batch_path = ANN_DIR / "researcher_batch_100.csv"
    if a1_path.exists() and batch_path.exists():
        a1 = pd.read_csv(a1_path, dtype=str).set_index("annotation_id")["label"].fillna("").str.strip()
        a1 = a1[a1 != ""]
        batch = pd.read_csv(batch_path, dtype=str).set_index("annotation_id")
        ids = a1.index.intersection(batch.index)
        if len(ids):
            human = {
                "status": "computed_from_human_annotation_file",
                "file": "data/annotation/annotator_1.csv",
                "indobert_vs_annotator_1": metrics(a1.loc[ids], batch.loc[ids, "indobert_prediction"].astype(str))
                | {"cohen_kappa": round(float(cohen_kappa_score(a1.loc[ids], batch.loc[ids, "indobert_prediction"].astype(str))), 4)},
                "silver_vs_annotator_1": metrics(a1.loc[ids], batch.loc[ids, "silver_label"].astype(str)),
                "inter_rater": "see results/MULTI_ANNOTATOR_GOLD_VALIDATION_REPORT.json (requires annotator_2.csv)",
            }

    out = {"generated_at": datetime.now(timezone.utc).isoformat(),
           "holdout_v2_vs_silver": holdout, "human_annotation": human}
    (RESULTS_DIR / "INDOBERT_ACTUAL_HUMAN_VALIDATION_REPORT.json").write_text(
        json.dumps(out, indent=2, ensure_ascii=False), encoding="utf-8")
    (REPORTS_DIR / "iaa_expert_model_agreement.json").write_text(
        json.dumps({"generated_at": out["generated_at"], "human_annotation": human}, indent=2, ensure_ascii=False),
        encoding="utf-8")

    h = holdout
    md = [
        "# Validasi IndoBERT",
        "",
        "## 1. Holdout group-aware (protokol v2) terhadap label silver-standard",
        "",
        f"- n = {h['n']} | akurasi {h['accuracy']:.2%} | macro-F1 {h['macro_f1']} | weighted-F1 {h['weighted_f1']}",
        f"- macro-precision {h['macro_precision']} | macro-recall {h['macro_recall']}",
        "- Label acuan: silver-standard (berbasis kata kunci/aturan), bukan anotasi manusia.",
        "- Kelas tanpa sampel di set uji: Bahagia, Kaget, Takut.",
        "",
        "| Kelas | Precision | Recall | F1 | Support |",
        "|---|---|---|---|---|",
    ] + [f"| {k} | {v['precision']} | {v['recall']} | {v['f1-score']} | {v['support']} |" for k, v in h["per_class"].items()] + [
        "",
        "## 2. Anotasi manusia",
        "",
        f"- Status: {human['status']}",
    ]
    if human["status"] == "not_available":
        md.append(f"- {human['note']}")
    (RESULTS_DIR / "INDOBERT_ACTUAL_HUMAN_VALIDATION_REPORT.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()

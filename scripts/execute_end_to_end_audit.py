import os
import sys
import json
import torch
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.model_selection import train_test_split, GroupShuffleSplit
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.linear_model import LogisticRegression
from sklearn.svm import LinearSVC
from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    classification_report,
    confusion_matrix
)
from transformers import AutoTokenizer, AutoModelForSequenceClassification, Trainer, TrainingArguments

def run_end_to_end():
    print("=" * 80)
    print("END-TO-END AUDIT & EXPERIMENT PIPELINE: TIME-E 2026 / IEEE")
    print("=" * 80)

    base_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    results_dir = os.path.join(base_dir, "results")
    os.makedirs(results_dir, exist_ok=True)

    # =========================================================================
    # BAGIAN 1 — AUDIT DATASET EMOSI
    # =========================================================================
    print("\n>>> BAGIAN 1: AUDIT DATASET EMOSI")
    data_path = os.path.join(base_dir, "data", "results", "indobert_9_emosi_fixed.csv")
    df = pd.read_csv(data_path)

    total_rows = len(df)
    columns_list = df.columns.tolist()
    dtypes_dict = {col: str(dtype) for col, dtype in df.dtypes.items()}
    missing_dict = df.isnull().sum().to_dict()
    dup_rows = int(df.duplicated().sum())
    dup_text = int(df['text'].duplicated().sum())
    dup_proc = int(df['processed_text'].duplicated().sum())
    unique_text_cnt = int(df['text'].nunique())
    unique_proc_cnt = int(df['processed_text'].nunique())

    label_counts = df['predicted_emotion'].value_counts().to_dict()
    unique_labels = list(label_counts.keys())
    theoretical_9 = ['Marah', 'Jijik', 'Takut', 'Bahagia', 'Percaya', 'Netral', 'Sedih', 'Tertarik', 'Kaget']
    missing_labels = [l for l in theoretical_9 if l not in unique_labels]

    # Save 01_dataset_audit.csv
    audit_summary_data = [
        {"metric": "total_rows", "value": total_rows},
        {"metric": "total_columns", "value": len(columns_list)},
        {"metric": "duplicate_rows_full", "value": dup_rows},
        {"metric": "duplicate_raw_text", "value": dup_text},
        {"metric": "duplicate_processed_text", "value": dup_proc},
        {"metric": "unique_raw_text", "value": unique_text_cnt},
        {"metric": "unique_processed_text", "value": unique_proc_cnt},
        {"metric": "num_unique_labels_present", "value": len(unique_labels)},
        {"metric": "missing_theoretical_labels", "value": ", ".join(missing_labels)},
    ]
    pd.DataFrame(audit_summary_data).to_csv(os.path.join(results_dir, "01_dataset_audit.csv"), index=False)

    # Document provenance as silver-standard reference labels
    audit_md_content = f"""# 01 Dataset Audit & Label Provenance Report

## 1. Dataset Overview
- **File Path:** `{data_path}`
- **Total Records:** {total_rows}
- **Columns ({len(columns_list)}):** {', '.join(columns_list)}
- **Data Types:** {json.dumps(dtypes_dict, indent=2)}
- **Missing Values:** {json.dumps(missing_dict, indent=2)}

## 2. Text Duplication
- **Full Row Duplicates:** {dup_rows}
- **Raw Text (`text`) Duplicates:** {dup_text} (Unique Texts: {unique_text_cnt})
- **Processed Text (`processed_text`) Duplicates:** {dup_proc} (Unique Processed Texts: {unique_proc_cnt})

## 3. Class Distribution
| Emotion Label | Indonesian | Theoretical Mapping | Count (N) | Percentage (%) |
| :--- | :--- | :--- | :--- | :--- |
| **Jijik** | Jijik | Disgust | {label_counts.get('Jijik', 0)} | {label_counts.get('Jijik', 0)/total_rows*100:.2f}% |
| **Percaya** | Percaya | Trust / Love | {label_counts.get('Percaya', 0)} | {label_counts.get('Percaya', 0)/total_rows*100:.2f}% |
| **Netral** | Netral | Neutral | {label_counts.get('Netral', 0)} | {label_counts.get('Netral', 0)/total_rows*100:.2f}% |
| **Tertarik** | Tertarik | Interest / Shame | {label_counts.get('Tertarik', 0)} | {label_counts.get('Tertarik', 0)/total_rows*100:.2f}% |
| **Marah** | Marah | Anger | {label_counts.get('Marah', 0)} | {label_counts.get('Marah', 0)/total_rows*100:.2f}% |
| **Sedih** | Sedih | Sadness | {label_counts.get('Sedih', 0)} | {label_counts.get('Sedih', 0)/total_rows*100:.2f}% |
| **Takut** | Takut | Fear | {label_counts.get('Takut', 0)} | {label_counts.get('Takut', 0)/total_rows*100:.2f}% |
| **Bahagia** | Bahagia | Joy | 0 | 0.00% (Missing) |
| **Kaget** | Kaget | Surprise | 0 | 0.00% (Missing) |

## 4. Label Provenance & Terminology Standard
- **Column Used:** `predicted_emotion`
- **Audit Findings:** Traced via `scripts/PERBAIKAN_LABELING.py` and `tesis_text.txt` line 310.
- **Academic Classification:** **silver-standard reference labels** generated by an automated annotation pipeline (Gemini API + rule-based heuristic lexicon filters).
- **Mandatory Constraint:** This column must NEVER be described as "human-annotated ground truth".
"""
    with open(os.path.join(results_dir, "01_dataset_audit.md"), "w", encoding="utf-8") as f:
        f.write(audit_md_content)
    print(" [DONE] Bagian 1 selesai: 01_dataset_audit.csv & 01_dataset_audit.md tersimpan.")

    # =========================================================================
    # BAGIAN 2 — AUDIT DUPLIKASI DAN KONFLIK LABEL
    # =========================================================================
    print("\n>>> BAGIAN 2: AUDIT DUPLIKASI DAN KONFLIK LABEL")
    # Group by text
    text_grp = df.groupby('text').agg(
        occurrence_count=('predicted_emotion', 'count'),
        unique_labels_count=('predicted_emotion', 'nunique'),
        labels_list=('predicted_emotion', lambda x: list(set(x)))
    ).reset_index()

    dup_groups = text_grp[text_grp['occurrence_count'] > 1]
    total_dup_groups = len(dup_groups)
    total_dup_rows = int(dup_groups['occurrence_count'].sum())
    conflicting_groups = dup_groups[dup_groups['unique_labels_count'] > 1]
    total_conflict_groups = len(conflicting_groups)
    total_conflict_rows = int(conflicting_groups['occurrence_count'].sum())

    dup_analysis_df = text_grp[text_grp['occurrence_count'] > 1].copy()
    dup_analysis_df['is_conflict'] = dup_analysis_df['unique_labels_count'] > 1
    dup_analysis_df['status'] = np.where(dup_analysis_df['is_conflict'], 'label conflict', 'identical label duplicate')
    dup_analysis_df.to_csv(os.path.join(results_dir, "02_duplicate_analysis.csv"), index=False)

    print(f" - Total duplicate groups: {total_dup_groups}")
    print(f" - Total duplicated rows: {total_dup_rows}")
    print(f" - Conflicting-label groups: {total_conflict_groups}")
    print(f" - Conflicting-label rows: {total_conflict_rows}")
    print(" [DONE] Bagian 2 selesai: 02_duplicate_analysis.csv tersimpan.")

    # =========================================================================
    # BAGIAN 3 — GROUP-AWARE SPLIT
    # =========================================================================
    print("\n>>> BAGIAN 3: GROUP-AWARE SPLIT (Zero-Leakage)")
    # Group by processed_text to ensure neither raw text nor processed_text leaks
    gss = GroupShuffleSplit(n_splits=1, test_size=0.2, random_state=42)
    train_idx, test_idx = next(gss.split(df, groups=df['processed_text']))

    train_df = df.iloc[train_idx].copy().reset_index(drop=True)
    test_df = df.iloc[test_idx].copy().reset_index(drop=True)

    # Programmatic verification of intersection
    raw_overlap = set(train_df['text']).intersection(set(test_df['text']))
    proc_overlap = set(train_df['processed_text']).intersection(set(test_df['processed_text']))

    print(f" - Programmatic raw text overlap: {len(raw_overlap)}")
    print(f" - Programmatic processed text overlap: {len(proc_overlap)}")

    if len(raw_overlap) != 0 or len(proc_overlap) != 0:
        raise ValueError(f"FATAL: Split leakage detected! raw_overlap={len(raw_overlap)}, proc_overlap={len(proc_overlap)}")

    # Save split datasets
    train_df.to_csv(os.path.join(results_dir, "emotion_train_group_split.csv"), index=False)
    test_df.to_csv(os.path.join(results_dir, "emotion_test_group_split.csv"), index=False)

    train_label_dist = train_df['predicted_emotion'].value_counts().to_dict()
    test_label_dist = test_df['predicted_emotion'].value_counts().to_dict()

    group_split_audit_md = f"""# 03 Group-Aware Split Audit Report

## 1. Protocol Specifications
- **Split Method:** `GroupShuffleSplit(n_splits=1, test_size=0.2, random_state=42)`
- **Grouping Entity:** `processed_text` (prevents representation & token-level leakage)
- **Train Records:** {len(train_df)} ({len(train_df)/len(df)*100:.2f}%)
- **Test Records:** {len(test_df)} ({len(test_df)/len(df)*100:.2f}%)

## 2. Programmatic Verification
- **Exact Raw Text Overlap (`text`):** {len(raw_overlap)} (PASSED: Exactly 0)
- **Exact Processed Text Overlap (`processed_text`):** {len(proc_overlap)} (PASSED: Exactly 0)
- **OVERLAP TEXT = 0**: VERIFIED

## 3. Label Distribution Across Splits
| Emotion Class | Train Count (N) | Train Pct (%) | Test Count (N) | Test Pct (%) |
| :--- | :--- | :--- | :--- | :--- |
| **Jijik** | {train_label_dist.get('Jijik', 0)} | {train_label_dist.get('Jijik', 0)/len(train_df)*100:.2f}% | {test_label_dist.get('Jijik', 0)} | {test_label_dist.get('Jijik', 0)/len(test_df)*100:.2f}% |
| **Percaya** | {train_label_dist.get('Percaya', 0)} | {train_label_dist.get('Percaya', 0)/len(train_df)*100:.2f}% | {test_label_dist.get('Percaya', 0)} | {test_label_dist.get('Percaya', 0)/len(test_df)*100:.2f}% |
| **Netral** | {train_label_dist.get('Netral', 0)} | {train_label_dist.get('Netral', 0)/len(train_df)*100:.2f}% | {test_label_dist.get('Netral', 0)} | {test_label_dist.get('Netral', 0)/len(test_df)*100:.2f}% |
| **Tertarik** | {train_label_dist.get('Tertarik', 0)} | {train_label_dist.get('Tertarik', 0)/len(train_df)*100:.2f}% | {test_label_dist.get('Tertarik', 0)} | {test_label_dist.get('Tertarik', 0)/len(test_df)*100:.2f}% |
| **Marah** | {train_label_dist.get('Marah', 0)} | {train_label_dist.get('Marah', 0)/len(train_df)*100:.2f}% | {test_label_dist.get('Marah', 0)} | {test_label_dist.get('Marah', 0)/len(test_df)*100:.2f}% |
| **Sedih** | {train_label_dist.get('Sedih', 0)} | {train_label_dist.get('Sedih', 0)/len(train_df)*100:.2f}% | {test_label_dist.get('Sedih', 0)} | {test_label_dist.get('Sedih', 0)/len(test_df)*100:.2f}% |
| **Takut** | {train_label_dist.get('Takut', 0)} | {train_label_dist.get('Takut', 0)/len(train_df)*100:.2f}% | {test_label_dist.get('Takut', 0)} | {test_label_dist.get('Takut', 0)/len(test_df)*100:.2f}% |
"""
    with open(os.path.join(results_dir, "03_group_split_audit.md"), "w", encoding="utf-8") as f:
        f.write(group_split_audit_md)
    print(" [DONE] Bagian 3 selesai: emotion_train/test_group_split.csv & 03_group_split_audit.md tersimpan.")

    # =========================================================================
    # BAGIAN 4 — BASELINE TF-IDF + LOGISTIC REGRESSION
    # =========================================================================
    print("\n>>> BAGIAN 4: BASELINE TF-IDF + LOGISTIC REGRESSION (Group-Aware)")
    tfidf = TfidfVectorizer(max_features=5000, ngram_range=(1, 2))
    # Fit vectorizer ONLY on training set
    X_train_tfidf = tfidf.fit_transform(train_df['processed_text'])
    X_test_tfidf = tfidf.transform(test_df['processed_text'])

    y_train = train_df['predicted_emotion'].values
    y_test = test_df['predicted_emotion'].values

    # Logistic Regression with class_weight='balanced' or standard
    # Using standard first to evaluate unweighted baseline
    lr = LogisticRegression(max_iter=1000, random_state=42)
    lr.fit(X_train_tfidf, y_train)
    lr_preds = lr.predict(X_test_tfidf)

    lr_acc = accuracy_score(y_test, lr_preds)
    lr_macro_p = precision_score(y_test, lr_preds, average='macro', zero_division=0)
    lr_macro_r = recall_score(y_test, lr_preds, average='macro', zero_division=0)
    lr_macro_f1 = f1_score(y_test, lr_preds, average='macro', zero_division=0)
    lr_weight_p = precision_score(y_test, lr_preds, average='weighted', zero_division=0)
    lr_weight_r = recall_score(y_test, lr_preds, average='weighted', zero_division=0)
    lr_weight_f1 = f1_score(y_test, lr_preds, average='weighted', zero_division=0)

    lr_report_dict = classification_report(y_test, lr_preds, digits=4, zero_division=0, output_dict=True)
    pd.DataFrame(lr_report_dict).transpose().reset_index().rename(columns={'index': 'Emotion'}).to_csv(
        os.path.join(results_dir, "04_tfidf_logreg_report.csv"), index=False
    )
    print(f" - LR Accuracy: {lr_acc:.4f}, Macro-F1: {lr_macro_f1:.4f}, Weighted-F1: {lr_weight_f1:.4f}")
    print(" [DONE] Bagian 4 selesai: 04_tfidf_logreg_report.csv tersimpan.")

    # =========================================================================
    # BAGIAN 5 — BASELINE TF-IDF + LINEAR SVM
    # =========================================================================
    print("\n>>> BAGIAN 5: BASELINE TF-IDF + LINEAR SVM (Group-Aware)")
    svm = LinearSVC(max_iter=2000, random_state=42)
    svm.fit(X_train_tfidf, y_train)
    svm_preds = svm.predict(X_test_tfidf)

    svm_acc = accuracy_score(y_test, svm_preds)
    svm_macro_p = precision_score(y_test, svm_preds, average='macro', zero_division=0)
    svm_macro_r = recall_score(y_test, svm_preds, average='macro', zero_division=0)
    svm_macro_f1 = f1_score(y_test, svm_preds, average='macro', zero_division=0)
    svm_weight_p = precision_score(y_test, svm_preds, average='weighted', zero_division=0)
    svm_weight_r = recall_score(y_test, svm_preds, average='weighted', zero_division=0)
    svm_weight_f1 = f1_score(y_test, svm_preds, average='weighted', zero_division=0)

    svm_report_dict = classification_report(y_test, svm_preds, digits=4, zero_division=0, output_dict=True)
    pd.DataFrame(svm_report_dict).transpose().reset_index().rename(columns={'index': 'Emotion'}).to_csv(
        os.path.join(results_dir, "05_tfidf_svm_report.csv"), index=False
    )
    print(f" - SVM Accuracy: {svm_acc:.4f}, Macro-F1: {svm_macro_f1:.4f}, Weighted-F1: {svm_weight_f1:.4f}")
    print(" [DONE] Bagian 5 selesai: 05_tfidf_svm_report.csv tersimpan.")

    # =========================================================================
    # BAGIAN 6 — AUDIT CHECKPOINT INDOBERT (checkpoint-792)
    # =========================================================================
    print("\n>>> BAGIAN 6: AUDIT CHECKPOINT INDOBERT (checkpoint-792)")
    checkpoint_dir = os.path.join(results_dir, "indobert_finetuned_9_labels", "checkpoint-792")
    config_file = os.path.join(checkpoint_dir, "config.json")
    with open(config_file, "r") as f:
        cfg = json.load(f)

    trainer_state_file = os.path.join(checkpoint_dir, "trainer_state.json")
    with open(trainer_state_file, "r") as f:
        t_state = json.load(f)

    checkpoint_audit_md = f"""# 06 IndoBERT Checkpoint Audit Report

## 1. Checkpoint Artifact Metadata
- **Path:** `{checkpoint_dir}`
- **Model Architecture:** `{cfg.get('architectures', ['Unknown'])[0]}`
- **Model Type:** `{cfg.get('model_type', 'bert')}`
- **Number of Labels:** {cfg.get('num_labels')}
- **Label Mapping (`id2label`):** {json.dumps(cfg.get('id2label'), indent=2)}
- **Training Epochs:** {t_state.get('epoch')}
- **Global Training Steps:** {t_state.get('global_step')}

## 2. Split Reconstruction & Provenance Investigation
- Evidence from `scripts/train.py` line 30:
  `train_texts, val_texts, train_labels, val_labels = train_test_split(df['processed_text'].tolist(), df['label_id'].tolist(), test_size=0.2, random_state=42)`
- **Finding:** The training script used standard `sklearn.model_selection.train_test_split` with `random_state=42` and `test_size=0.2`.
- **Crucial Flaw:** It did NOT perform group-aware splitting. Duplicate texts were randomly scattered across both training and evaluation partitions.
"""
    with open(os.path.join(results_dir, "06_indobert_checkpoint_audit.md"), "w", encoding="utf-8") as f:
        f.write(checkpoint_audit_md)
    print(" [DONE] Bagian 6 selesai: 06_indobert_checkpoint_audit.md tersimpan.")

    # =========================================================================
    # BAGIAN 7 — DETEKSI LEAKAGE CHECKPOINT LAMA
    # =========================================================================
    print("\n>>> BAGIAN 7: DETEKSI LEAKAGE CHECKPOINT LAMA")
    # Reconstruct original split
    label_to_id = {
        'Marah': 0, 'Jijik': 1, 'Takut': 2, 'Bahagia': 3,
        'Percaya': 4, 'Netral': 5, 'Sedih': 6, 'Tertarik': 7, 'Kaget': 8
    }
    id_to_label = {v: k for k, v in label_to_id.items()}

    df_orig = df.dropna(subset=['processed_text', 'predicted_emotion']).copy()
    df_orig['label_id'] = df_orig['predicted_emotion'].map(label_to_id).astype(int)

    orig_train_texts, orig_test_texts, orig_train_labels, orig_test_labels = train_test_split(
        df_orig['processed_text'].tolist(),
        df_orig['label_id'].tolist(),
        test_size=0.2,
        random_state=42
    )

    orig_train_set = set(orig_train_texts)
    orig_test_set = set(orig_test_texts)
    leakage_texts = orig_train_set.intersection(orig_test_set)
    test_rows_leaked = sum(1 for t in orig_test_texts if t in orig_train_set)

    print(f" - Unique overlapping text strings: {len(leakage_texts)}")
    print(f" - Total test rows affected by leakage: {test_rows_leaked} of {len(orig_test_texts)} ({test_rows_leaked/len(orig_test_texts)*100:.2f}%)")

    if len(leakage_texts) > 0:
        leakage_status = "LEAKAGE_DETECTED"
    else:
        leakage_status = "NO_TEXT_LEAKAGE_DETECTED"
    print(f" - Status Leakage Checkpoint Lama: {leakage_status}")

    # =========================================================================
    # BAGIAN 8 — EVALUASI CHECKPOINT LAMA PADA ORIGINAL PROTOCOL
    # =========================================================================
    print("\n>>> BAGIAN 8: EVALUASI CHECKPOINT LAMA (Original Protocol - Diagnostic)")
    device = torch.device("mps" if torch.backends.mps.is_available() else ("cuda" if torch.cuda.is_available() else "cpu"))
    tokenizer = AutoTokenizer.from_pretrained("indobenchmark/indobert-base-p2")
    old_model = AutoModelForSequenceClassification.from_pretrained(checkpoint_dir).to(device)
    old_model.eval()

    def predict_texts(model, texts, b_size=32):
        all_preds = []
        for i in range(0, len(texts), b_size):
            b_texts = texts[i:i+b_size]
            inputs = tokenizer(b_texts, padding=True, truncation=True, max_length=128, return_tensors="pt").to(device)
            with torch.no_grad():
                logits = model(**inputs).logits
                preds = torch.argmax(logits, dim=1).cpu().numpy().tolist()
                all_preds.extend(preds)
        return all_preds

    old_orig_preds = predict_texts(old_model, orig_test_texts)

    old_orig_acc = accuracy_score(orig_test_labels, old_orig_preds)
    old_orig_macro_p = precision_score(orig_test_labels, old_orig_preds, average='macro', zero_division=0)
    old_orig_macro_r = recall_score(orig_test_labels, old_orig_preds, average='macro', zero_division=0)
    old_orig_macro_f1 = f1_score(orig_test_labels, old_orig_preds, average='macro', zero_division=0)
    old_orig_weight_f1 = f1_score(orig_test_labels, old_orig_preds, average='weighted', zero_division=0)

    # Save 07_indobert_original_protocol.csv
    old_orig_classes = sorted(list(set(orig_test_labels).union(set(old_orig_preds))))
    old_orig_class_names = [id_to_label[c] for c in old_orig_classes]
    old_orig_report = classification_report(
        orig_test_labels, old_orig_preds, labels=old_orig_classes,
        target_names=old_orig_class_names, digits=4, zero_division=0, output_dict=True
    )
    pd.DataFrame(old_orig_report).transpose().reset_index().rename(columns={'index': 'Emotion'}).to_csv(
        os.path.join(results_dir, "07_indobert_original_protocol.csv"), index=False
    )

    # Confusion matrix
    cm_orig = confusion_matrix(orig_test_labels, old_orig_preds, labels=old_orig_classes)
    plt.figure(figsize=(9, 7))
    sns.heatmap(cm_orig, annot=True, fmt='d', cmap='Blues', xticklabels=old_orig_class_names, yticklabels=old_orig_class_names)
    plt.xlabel('Predicted (IndoBERT Checkpoint-792)', fontsize=11, fontweight='bold')
    plt.ylabel('Actual (Original Protocol Silver)', fontsize=11, fontweight='bold')
    plt.title('Confusion Matrix: IndoBERT Checkpoint-792 (Original Protocol - LEAKAGE DETECTED)', fontsize=12, fontweight='bold')
    plt.tight_layout()
    plt.savefig(os.path.join(results_dir, "07_indobert_original_confusion_matrix.png"), dpi=300)
    plt.close()
    print(" [DONE] Bagian 8 selesai: 07_indobert_original_protocol.csv & png tersimpan.")

    # =========================================================================
    # BAGIAN 9 — UJI FAIRNESS DENGAN GROUP-AWARE TEST SET
    # =========================================================================
    print("\n>>> BAGIAN 9: UJI FAIRNESS CHECKPOINT LAMA (Group-Aware Test Set - Diagnostic)")
    # Test on test_df from Bagian 3
    test_proc_texts = test_df['processed_text'].tolist()
    test_num_labels = [label_to_id[l] for l in test_df['predicted_emotion'].tolist()]

    old_group_preds = predict_texts(old_model, test_proc_texts)

    old_group_acc = accuracy_score(test_num_labels, old_group_preds)
    old_group_macro_p = precision_score(test_num_labels, old_group_preds, average='macro', zero_division=0)
    old_group_macro_r = recall_score(test_num_labels, old_group_preds, average='macro', zero_division=0)
    old_group_macro_f1 = f1_score(test_num_labels, old_group_preds, average='macro', zero_division=0)
    old_group_weight_f1 = f1_score(test_num_labels, old_group_preds, average='weighted', zero_division=0)

    print(f" - Checkpoint-792 on Group-Aware Test Set: Accuracy={old_group_acc:.4f}, Macro-F1={old_group_macro_f1:.4f}, Weighted-F1={old_group_weight_f1:.4f}")
    print("   [TAG]: NOT_VALID_FOR_GENERALIZATION (Checkpoint-792 may have seen train duplicates in its original training)")

    # =========================================================================
    # BAGIAN 10 — KEPUTUSAN OTOMATIS APAKAH INDOBERT PERLU RETRAINING
    # =========================================================================
    print("\n>>> BAGIAN 10: KEPUTUSAN OTOMATIS RETRAINING")
    needs_retraining = (
        leakage_status == "LEAKAGE_DETECTED" or
        len(leakage_texts) > 0
    )
    if needs_retraining:
        retraining_status = "REQUIRES_RETRAINING"
